const getKstTodayString = () => {
  try {
    const d = new Date();
    const parts = new Intl.DateTimeFormat('ko-KR', {
      timeZone: 'Asia/Seoul',
      year: 'numeric',
      month: 'numeric',
      day: 'numeric'
    }).formatToParts(d);
    const getPart = (type: string) => parts.find(p => p.type === type)?.value || '';
    return `${getPart('year')}년 ${getPart('month')}월 ${getPart('day')}일`;
  } catch {
    return '2026년 10월 11일';
  }
};

